/**
 * Get ISO country code from country name
 * @param countryName - Full country name (e.g., "Saudi Arabia")
 * @returns ISO 3166-1 alpha-2 code (e.g., "SA") or null if not found
 */
export function getIsoCountryCode(countryName: string): IsoCountryCode | null {
    if (!countryName) return null;
    
    // Trim and normalize
    const normalized = countryName.trim();
    
    // Check if already an ISO code (2 letters)
    if (normalized.length === 2 && /^[A-Z]{2}$/i.test(normalized)) {
        return normalized.toUpperCase() as IsoCountryCode;
    }
    
    // Look up by common name
    return CountryNameToIsoCode[normalized] || null;
}